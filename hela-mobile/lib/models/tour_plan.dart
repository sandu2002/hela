// Data models for AI-generated tour plans and itineraries.

import 'package:hela/models/destination.dart';

/// A single activity within an itinerary day.
class ItineraryActivity {
  /// Activity title (e.g., "Visit Sigiriya Rock Fortress").
  final String title;

  /// Detailed description of the activity.
  final String description;

  /// Destination associated with this activity (if applicable).
  final Destination? destination;

  /// Suggested start time (e.g., "08:00 AM").
  final String startTime;

  /// Estimated duration (e.g., "2 hours").
  final String estimatedDuration;

  /// Activity category/type.
  final String category;

  /// Estimated cost in USD (marked as estimated).
  final double? estimatedCostUsd;

  /// Whether the cost is an AI estimate vs. verified source data.
  final bool isCostEstimated;

  /// Estimated travel time from previous activity.
  final String? travelTimeFromPrevious;

  /// Travel method from previous activity (e.g., "by car", "walking").
  final String? travelMethod;

  /// Travel tips specific to this activity.
  final List<String> tips;

  const ItineraryActivity({
    required this.title,
    this.description = '',
    this.destination,
    this.startTime = '',
    this.estimatedDuration = '',
    this.category = '',
    this.estimatedCostUsd,
    this.isCostEstimated = true,
    this.travelTimeFromPrevious,
    this.travelMethod,
    this.tips = const [],
  });

  factory ItineraryActivity.fromJson(Map<String, dynamic> json) {
    return ItineraryActivity(
      title: json['title'] as String? ?? 'Activity',
      description: json['description'] as String? ?? '',
      destination: json['destination'] != null
          ? Destination.fromJson(json['destination'] as Map<String, dynamic>)
          : null,
      startTime: json['startTime'] as String? ?? '',
      estimatedDuration: json['estimatedDuration'] as String? ?? '',
      category: json['category'] as String? ?? '',
      estimatedCostUsd: (json['estimatedCostUsd'] as num?)?.toDouble(),
      isCostEstimated: json['isCostEstimated'] as bool? ?? true,
      travelTimeFromPrevious: json['travelTimeFromPrevious'] as String?,
      travelMethod: json['travelMethod'] as String?,
      tips:
          (json['tips'] as List<dynamic>?)?.map((e) => e.toString()).toList() ??
          [],
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'title': title,
      'description': description,
      if (destination != null) 'destination': destination!.toJson(),
      'startTime': startTime,
      'estimatedDuration': estimatedDuration,
      'category': category,
      if (estimatedCostUsd != null) 'estimatedCostUsd': estimatedCostUsd,
      'isCostEstimated': isCostEstimated,
      if (travelTimeFromPrevious != null)
        'travelTimeFromPrevious': travelTimeFromPrevious,
      if (travelMethod != null) 'travelMethod': travelMethod,
      'tips': tips,
    };
  }
}

/// A single day in the itinerary.
class ItineraryDay {
  /// Day number (1-indexed).
  final int dayNumber;

  /// Theme/title for this day (e.g., "Highland Tea Country").
  final String title;

  /// Summary of the day's experience.
  final String summary;

  /// Ordered list of activities for this day.
  final List<ItineraryActivity> activities;

  /// Estimated total cost for this day in USD.
  final double? estimatedDayCostUsd;

  /// Overnight accommodation suggestion.
  final String? overnightStay;

  const ItineraryDay({
    required this.dayNumber,
    this.title = '',
    this.summary = '',
    this.activities = const [],
    this.estimatedDayCostUsd,
    this.overnightStay,
  });

  factory ItineraryDay.fromJson(Map<String, dynamic> json) {
    return ItineraryDay(
      dayNumber: json['dayNumber'] as int? ?? 1,
      title: json['title'] as String? ?? '',
      summary: json['summary'] as String? ?? '',
      activities:
          (json['activities'] as List<dynamic>?)
              ?.map(
                (e) => ItineraryActivity.fromJson(e as Map<String, dynamic>),
              )
              .toList() ??
          [],
      estimatedDayCostUsd: (json['estimatedDayCostUsd'] as num?)?.toDouble(),
      overnightStay: json['overnightStay'] as String?,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'dayNumber': dayNumber,
      'title': title,
      'summary': summary,
      'activities': activities.map((a) => a.toJson()).toList(),
      if (estimatedDayCostUsd != null)
        'estimatedDayCostUsd': estimatedDayCostUsd,
      if (overnightStay != null) 'overnightStay': overnightStay,
    };
  }
}

/// A complete tour plan generated by the AI.
class TourPlan {
  /// Unique plan ID (UUID).
  final String id;

  /// Tour title (e.g., "Highland Sanctuary & Mist Route").
  final String title;

  /// Tour summary / overview.
  final String summary;

  /// Why this tour matches the user's preferences.
  final String matchReason;

  /// Total duration in days.
  final int durationDays;

  /// Day-by-day itinerary.
  final List<ItineraryDay> days;

  /// Estimated total cost in USD per person.
  final double? estimatedTotalCostUsd;

  /// Budget breakdown description.
  final String budgetBreakdown;

  /// What the budget estimate includes.
  final List<String> budgetIncludes;

  /// What the budget estimate does NOT include.
  final List<String> budgetExcludes;

  /// General travel tips for this tour.
  final List<String> travelTips;

  /// Warnings or important notes.
  final List<String> warnings;

  /// Data sources used for this plan.
  final List<String> dataSources;

  /// Plan version (incremented on each customization).
  final int version;

  /// ISO 8601 timestamp of when this plan was generated.
  final String generatedAt;

  /// Customization summary (what changed in the latest version).
  final String? customizationSummary;

  /// Whether this plan has been saved by the user.
  final bool isSaved;

  const TourPlan({
    required this.id,
    required this.title,
    this.summary = '',
    this.matchReason = '',
    required this.durationDays,
    this.days = const [],
    this.estimatedTotalCostUsd,
    this.budgetBreakdown = '',
    this.budgetIncludes = const [],
    this.budgetExcludes = const [],
    this.travelTips = const [],
    this.warnings = const [],
    this.dataSources = const [],
    this.version = 1,
    this.generatedAt = '',
    this.customizationSummary,
    this.isSaved = false,
  });

  factory TourPlan.fromJson(Map<String, dynamic> json) {
    return TourPlan(
      id: json['id'] as String? ?? '',
      title: json['title'] as String? ?? 'Tour Plan',
      summary: json['summary'] as String? ?? '',
      matchReason: json['matchReason'] as String? ?? '',
      durationDays: json['durationDays'] as int? ?? 1,
      days:
          (json['days'] as List<dynamic>?)
              ?.map((e) => ItineraryDay.fromJson(e as Map<String, dynamic>))
              .toList() ??
          [],
      estimatedTotalCostUsd: (json['estimatedTotalCostUsd'] as num?)
          ?.toDouble(),
      budgetBreakdown: json['budgetBreakdown'] as String? ?? '',
      budgetIncludes:
          (json['budgetIncludes'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      budgetExcludes:
          (json['budgetExcludes'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      travelTips:
          (json['travelTips'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      warnings:
          (json['warnings'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      dataSources:
          (json['dataSources'] as List<dynamic>?)
              ?.map((e) => e.toString())
              .toList() ??
          [],
      version: json['version'] as int? ?? 1,
      generatedAt: json['generatedAt'] as String? ?? '',
      customizationSummary: json['customizationSummary'] as String?,
      isSaved: json['isSaved'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'summary': summary,
      'matchReason': matchReason,
      'durationDays': durationDays,
      'days': days.map((d) => d.toJson()).toList(),
      if (estimatedTotalCostUsd != null)
        'estimatedTotalCostUsd': estimatedTotalCostUsd,
      'budgetBreakdown': budgetBreakdown,
      'budgetIncludes': budgetIncludes,
      'budgetExcludes': budgetExcludes,
      'travelTips': travelTips,
      'warnings': warnings,
      'dataSources': dataSources,
      'version': version,
      'generatedAt': generatedAt,
      if (customizationSummary != null)
        'customizationSummary': customizationSummary,
      'isSaved': isSaved,
    };
  }

  /// Creates a copy with updated fields.
  TourPlan copyWith({
    String? id,
    String? title,
    String? summary,
    String? matchReason,
    int? durationDays,
    List<ItineraryDay>? days,
    double? estimatedTotalCostUsd,
    String? budgetBreakdown,
    List<String>? budgetIncludes,
    List<String>? budgetExcludes,
    List<String>? travelTips,
    List<String>? warnings,
    List<String>? dataSources,
    int? version,
    String? generatedAt,
    String? customizationSummary,
    bool? isSaved,
  }) {
    return TourPlan(
      id: id ?? this.id,
      title: title ?? this.title,
      summary: summary ?? this.summary,
      matchReason: matchReason ?? this.matchReason,
      durationDays: durationDays ?? this.durationDays,
      days: days ?? this.days,
      estimatedTotalCostUsd:
          estimatedTotalCostUsd ?? this.estimatedTotalCostUsd,
      budgetBreakdown: budgetBreakdown ?? this.budgetBreakdown,
      budgetIncludes: budgetIncludes ?? this.budgetIncludes,
      budgetExcludes: budgetExcludes ?? this.budgetExcludes,
      travelTips: travelTips ?? this.travelTips,
      warnings: warnings ?? this.warnings,
      dataSources: dataSources ?? this.dataSources,
      version: version ?? this.version,
      generatedAt: generatedAt ?? this.generatedAt,
      customizationSummary: customizationSummary ?? this.customizationSummary,
      isSaved: isSaved ?? this.isSaved,
    );
  }
}

/// Chat message model for the AI customization chat.
class ChatMessage {
  final String id;
  final String content;
  final bool isUser;
  final String timestamp;
  final TourPlan? updatedPlan;

  const ChatMessage({
    required this.id,
    required this.content,
    required this.isUser,
    required this.timestamp,
    this.updatedPlan,
  });
}
